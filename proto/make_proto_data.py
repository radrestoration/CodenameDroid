#!/usr/bin/env python3
"""Data for the C64-native engine prototype (proto/proto.s), from the BBC game's own level and sprite data.

  make_proto_data.py OUTDIR [LEVEL]

writes into OUTDIR:
  rows.bin     the level as character numbers, 32 rows of 256 cells (the level's 64 tiles x 4 cell columns, 8 tiles x 4 cell rows)
  bpat.bin     the BBC bytes of each character, line by line: 8 pages of 256 (line n of character c at n * 256 + c): what the
               game reads for collisions
  charset.bin  the characters as C64 multicolour patterns (2 KB)
  sprites.bin  the player's and the enemies' sprite blocks (64 bytes each): per kind, left-facing then right-facing, five
               frames, upper (21 lines) and lower (11 lines) halves
  proto_data.inc  the constants (start positions, number of characters)
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tools"))
import bbcmem as bm  # noqa: E402
import make_tables  # noqa: E402

PLAYER_SPRITES = [0x5bc0, 0x5c20, 0x5c80, 0x5ce0, 0x5d40]      # player_sprite_zero .. four: 3 bytes a line, 32 lines
ENEMY_SPRITES = [0x0a00, 0x0a60, 0x0ac0, 0x0b20, 0x0b80]       # enemy_sprite_zero .. four: 3 columns of 32 bytes


def level_cells(mem, level):
    """rows[row][col] of character numbers (0 = blank), the character list (BBC bytes) in order."""
    tiles = bm.level_tiles(mem, level)
    chars = [bytes(8)]
    index = {chars[0]: 0}
    rows = [[0] * 256 for _ in range(32)]
    for c in range(64):
        for ty in range(8):
            for xf in range(4):
                for k, cell in enumerate(bm.tile_cell_column(mem, tiles[c][ty], xf)):
                    if cell not in index:
                        index[cell] = len(chars)
                        chars.append(cell)
                    rows[ty * 4 + k][c * 4 + xf] = index[cell]
    return rows, chars


def sprite_rows(mem, addr, column_major):
    if column_major:
        return [[mem[addr + x * 32 + y] for x in range(3)] for y in range(32)]
    return [[mem[addr + y * 3 + x] for x in range(3)] for y in range(32)]


def flipped(rows):
    return [[bm.mirror_byte(b) for b in r[::-1]] for r in rows]


def blocks(rows, conv):
    """two 64-byte sprite blocks (C64 multicolour: three bytes a line): lines 0-20, lines 21-31 and blank"""
    c = [[conv[b] for b in r] for r in rows]
    top = bytes(v for r in c[:21] for v in r) + b"\0"
    bottom = bytes(v for r in c[21:] for v in r)
    return top + (bottom + bytes(64))[:64]


def main(outdir, level=1):
    os.makedirs(outdir, exist_ok=True)
    mem = bm.load()
    conv = make_tables.bbc_to_c64_table()
    rows, chars = level_cells(mem, level)
    assert len(chars) <= 256, len(chars)
    open(os.path.join(outdir, "rows.bin"), "wb").write(bytes(v for r in rows for v in r))
    bpat = bytearray(2048)
    charset = bytearray(2048)
    for i, ch in enumerate(chars):
        for line in range(8):
            bpat[line * 256 + i] = ch[line]
            charset[i * 8 + line] = conv[ch[line]]
    open(os.path.join(outdir, "bpat.bin"), "wb").write(bytes(bpat))
    open(os.path.join(outdir, "charset.bin"), "wb").write(bytes(charset))
    spr = bytearray()
    for addrs, colmajor in ((PLAYER_SPRITES, False), (ENEMY_SPRITES, True)):
        frames = [sprite_rows(mem, a, colmajor) for a in addrs]
        for f in frames:                                       # facing left: the sprites as they are
            spr += blocks(f, conv)
        for f in frames:                                       # facing right: mirrored
            spr += blocks(flipped(f), conv)
    open(os.path.join(outdir, "sprites.bin"), "wb").write(bytes(spr))

    # where the actors start: on the floor along the bottom, dropped from line 176 as the game's own checks land them
    def pixel(col, line):
        return chars[rows[line >> 3][col]][line & 7] if line < 256 else 0xff

    def free(col, y):
        return all(pixel(col + k, line) == 0 for k in range(3) for line in range(y, y + 32))

    def supported(col, y):
        return any(pixel(col + k, y + 32) for k in range(3))
    starts = []
    for col in range(4, 250):
        y = 176
        while y < 225 and free(col, y) and not supported(col, y):
            y += 4
        if y < 225 and free(col, y) and supported(col, y) and (not starts or col - starts[-1][0] >= 24):
            starts.append((col, y))
    print("level %d: %d characters; start points %s" % (level, len(chars), starts))
    with open(os.path.join(outdir, "proto_data.inc"), "w") as f:
        f.write("; generated by proto/make_proto_data.py\nNCHARS = %d\n" % len(chars))
        pc, py = starts[1]
        f.write("START_CX = %d\nSTART_Y = %d\n" % (pc, py))
        for i in range(3):
            c, y = starts[(3 + i * 2) % len(starts)]
            f.write("ENEMY%d_CX = %d\nENEMY%d_Y = %d\n" % (i, c, i, y))


if __name__ == "__main__":
    main(sys.argv[1], int(sys.argv[2]) if len(sys.argv) > 2 else 1)
