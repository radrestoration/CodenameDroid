#!/usr/bin/env python3
"""Lay out the Apple IIgs disk image (800 KB, 1600 blocks of 512 bytes, ProDOS order) and make the loader's table.

    make_apple2gs_disk.py prepare <profile>   write build/apple2gs/<profile>/loadtab.inc (and, for "game", game-iigs.bin)
    make_apple2gs_disk.py pack <profile>      write build/apple2gs/<profile>/<image>.po (needs boot.bin and the profile's stage1.bin)

Profiles: "game" (the C64 logic in bank 2 + platform and display layers, droid-gs.po) and "demo" (the earlier tile scroller, demo.po).

Disk: block 0 the boot block (boot.s), blocks 1 - 8 stage 1 (stage1.s), then each payload padded to whole blocks.
The load table (stage1.s reads it) says, for each payload, its first block, block count, destination address and bank.
Every payload must fit inside one bank and no two may overlap; a payload is copied in whole blocks, so up to 511 bytes
of zero padding land after its end."""
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
B = ROOT / "build" / "apple2gs"
BLOCK = 512
STAGE1_BLOCKS = int(re.search(r"STAGE1_BLOCKS\s*=\s*(\d+)", (ROOT / "hal/apple/gs/loader.inc").read_text()).group(1))
BLOCKS_ON_DISK = 1600

# per profile: (file, bank, address) in load order, the entry address, the entry symbol (in <labels>.lbl) and the image name.
# Order matters where blocks overlay: tramp.bin's 512 bytes end at $07FF, just below logic.bin's $0801.
PROFILES = {
    "demo": dict(payloads=[("demo.bin", 0x00, 0x2000), ("palette.bin", 0x00, 0x1C00), ("cells.bin", 0x02, 0x0000),
                           ("tiles.bin", 0x03, 0x0000), ("levels.bin", 0x03, 0x0A00)],
                 labels="demo.lbl", symbol="demo_start", image="demo.po"),
    "game": dict(payloads=[("game_code.bin", 0x00, 0x2000), ("palette.bin", 0x00, 0x1C00), ("bbc2shr.bin", 0x03, 0x0000),
                           ("tramp.bin", 0x02, 0x0600), ("logic.bin", 0x02, 0x0801), ("slam.bin", 0x03, 0xE400)],
                 labels="game_code.lbl", symbol=None, image="droid-gs.po"),
}


def labels(path):
    out = {}
    for line in path.read_text().splitlines():
        p = line.split()
        if len(p) == 3 and p[0] == "al":
            out[p[2].lstrip(".")] = int(p[1], 16)
    return out


def layout(profile):
    """[(name, data, first block, block count, bank, address)] and the entry address."""
    prof = PROFILES[profile]
    entry = labels(B / prof["labels"])[prof["symbol"]] if prof["symbol"] else 0x2000   # (the game's table of entry points starts at $2000)
    assert entry == 0x2000, f"the code is linked at $2000 and starts there, not ${entry:04X}"
    block = 1 + STAGE1_BLOCKS
    rows = []
    for name, bank, addr in prof["payloads"]:
        data = (B / name).read_bytes()
        count = -(-len(data) // BLOCK)
        assert addr + count * BLOCK <= 0x10000, f"{name} crosses a bank ({bank:02X}:{addr:04X} + {count} blocks)"
        rows.append((name, data, block, count, bank, addr))
        block += count
    assert block <= BLOCKS_ON_DISK, f"payloads need {block} blocks"
    for i, a in enumerate(rows):
        for b in rows[i + 1:]:
            if a[4] == b[4] and a[5] < b[5] + b[3] * BLOCK and b[5] < a[5] + a[3] * BLOCK:
                raise AssertionError(f"{a[0]} and {b[0]} overlap in bank {a[4]:02X}")
    return rows, entry


def prepare(profile):
    rows, entry = layout(profile)
    out = ["; generated by tools/make_apple2gs_disk.py - do not edit", "loadtab:"]
    for name, data, block, count, bank, addr in rows:
        out.append(f"        .word   {block}, {count}, ${addr:04x}       ; {name}: {len(data)} bytes")
        out.append(f"        .byte   ${bank:02x}, 0")
    out += ["        .word   0, 0, 0                 ; the end", "        .byte   0, 0", f"entry:  .word   ${entry:04x}"]
    (B / profile).mkdir(exist_ok=True)
    (B / profile / "loadtab.inc").write_text("\n".join(out) + "\n")
    print("loadtab.inc:", ", ".join(f"{r[0]} blocks {r[2]}-{r[2] + r[3] - 1}" for r in rows))


def pack(profile):
    rows, _ = layout(profile)
    boot = (B / "boot.bin").read_bytes()
    stage1 = (B / profile / "stage1.bin").read_bytes()
    assert len(boot) == BLOCK and boot[0] == 0x01
    assert len(stage1) <= 0xFE0 and len(stage1) <= STAGE1_BLOCKS * BLOCK, f"stage 1 is {len(stage1)} bytes"
    image = bytearray(boot)
    image += stage1.ljust(STAGE1_BLOCKS * BLOCK, b"\0")
    for name, data, block, count, bank, addr in rows:
        assert len(image) == block * BLOCK
        image += data.ljust(count * BLOCK, b"\0")
    image = image.ljust(BLOCKS_ON_DISK * BLOCK, b"\0")
    name = PROFILES[profile]["image"]
    (B / profile / name).write_bytes(image)
    print(f"{profile}/{name}: {len(image)} bytes, stage 1 {len(stage1)} bytes, {sum(r[3] for r in rows)} payload blocks")


if __name__ == "__main__":
    {"prepare": prepare, "pack": pack}[sys.argv[1]](sys.argv[2])
