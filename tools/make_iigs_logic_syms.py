#!/usr/bin/env python3
"""Write build/apple2gs/logic_syms.inc: where the game logic keeps what the IIgs platform and display layer read (label addresses
from build/apple2gs/logic.lbl; the memory map from src/memory.inc and the key numbers from src/constants.inc, parsed so that they
cannot drift)."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LABELS = ["nchars", "cur_buf", "level", "cur_w", "cur_cam", "compute_frame", "logic_start",
          "ready", "tick", "dt",
          "px", "py", "pc", "lives", "key1", "key2", "keys", "calc_scroll", "t_w", "t_xs", "spx_l", "spx_h", "spos_l", "spos_h", "p5", "p_sx", "p_sy", "p_ptr", "p_msb", "p_en"]
EQUATES = ["BPAT", "MAT_A", "MAT_B", "CH_EXPL1", "CH_EXPL0", "CH_MINE", "MAXCH", "ROWS", "MIRROR_TABLE", "SPRAREA"]


def main():
    lbl = {}
    for line in (ROOT / "build/apple2gs/logic.lbl").read_text().splitlines():
        p = line.split()
        if len(p) == 3 and p[0] == "al":
            lbl[p[2].lstrip(".")] = int(p[1], 16)
    equ = {}
    for name in ("src/memory.inc", "src/constants.inc"):
        for line in (ROOT / name).read_text().splitlines():
            m = re.match(r"^([A-Z][A-Z0-9_]*)\s*=\s*(\$[0-9a-fA-F]+|\d+)\b", line)
            if m:
                equ[m.group(1)] = int(m.group(2).lstrip("$"), 16 if m.group(2).startswith("$") else 10)
    out = ["; generated by tools/make_iigs_logic_syms.py - do not edit"]
    out += [f"L_{n} = ${lbl[n]:04x}" for n in LABELS]
    out += [f"L_{n} = ${equ[n]:04x}" for n in EQUATES]
    out += [f"{n} = {v}" for n, v in equ.items() if n.startswith("K_") or n == "KEYS"]    # the key numbers (K_RIGHT, ...)
    dest = ROOT / "build/apple2gs/logic_syms.inc"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(out) + "\n")
    print(dest.relative_to(ROOT), ", ".join(out[1:]))


if __name__ == "__main__":
    main()
