#!/usr/bin/env python3
"""Generate the C64's lookup tables: build/gen/tables.s

  bbc_to_c64   MODE 5 byte -> C64 multicolour byte (pixel n is bit 7-n and bit 3-n on the BBC;
               two adjacent bits, leftmost pixel in the top pair, on the C64). BBC logical
               colours 0-3 become the C64 pixel values 0-3, so the palette is
               background=black, %01=red ($d022), %10=cyan ($d023), %11=white (colour RAM).
  hash_tab     a permutation of 0-255, for hashing a cell's 8 bytes
  chandelier_class  per level byte: bit 0 = low nibble is a shrine chandelier (8), bit 1 = high nibble
  star_random  256 pseudo-random bytes: the BBC game reads its OS ROM at &e400+Y for the
               positions of the stars; the C64 has no such ROM, so this stands in.
"""
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bbcmem as bm  # noqa: E402


def star_table():
    """The BBC game reads its OS ROM at &e400+Y for the positions of the stars; the C64 has no such ROM: a table made at
    start-up (make_runtime_tables) stands in: the hash table's entry mixed with the index rotated."""
    h = hash_tab_table()
    return [h[x] ^ ((x << 3 | x >> 5) & 255) for x in range(256)]


def main(out):
    """tables.s: the four tables are made at start-up (platform.s make_runtime_tables, which tools/test_tables.py checks
    against the functions here) and only reserved here."""
    with open(out, "w") as f:
        f.write("; generated by tools/make_tables.py\n\n.segment \"TBLBSS\"\n\n")
        for name in ("star_random", "bbc_to_c64", "hash_tab", "chandelier_class"):
            f.write("%s:\n    .res 256\n" % name)
        import make_sound_tables
        make_sound_tables.emit(f)
    print("wrote", out)


def bbc_to_c64_table():
    t = []
    for b in range(256):
        p = bm.pixels(b)
        t.append(p[0] << 6 | p[1] << 4 | p[2] << 2 | p[3])
    return t


def chandelier_class_table():
    return [(1 if (b & 15) == 8 else 0) | (2 if (b & 0xf0) == 0x80 else 0) for b in range(256)]


def hash_tab_table():
    """A permutation of 0-255 made of steps that are each a permutation (multiplying by an odd number, an xor with a shift
    of itself): what make_runtime_tables does."""
    out = []
    for x in range(256):
        y = (x * 5 + 17) & 255
        y ^= y >> 3
        y = (y * 9 + 101) & 255
        y ^= (y << 2) & 255
        out.append(y)
    return out


if __name__ == "__main__":
    main(sys.argv[1])
