#!/usr/bin/env python3
"""Data for the C64-native game engine (native/), from the BBC game's own data.

  make_native_data.py OUTDIR

writes OUTDIR/native_data.inc (ca65 source: tables and binary blocks) and the sprite image blocks. Everything is in BBC
MODE 5 bytes unless it says C64: the engine converts through CONV when it makes characters.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bbcmem as bm  # noqa: E402
import make_tables  # noqa: E402

NUM_LEVELS = 12

PLAYER_STAND = [0x5bc0, 0x5c20, 0x5c80, 0x5ce0, 0x5d40]          # 3 bytes a line, 32 lines
PLAYER_KNEEL = 0x05e0
PLAYER_CLIMB = [0x0772, 0x0712]                                    # climbing zero, one
PLAYER_JET = 0x4920
PLAYER_CRAWL = [0x06a9, 0x0640]                                    # crawling two (frame 0), one (frame 1): 7 bytes a line, 15 lines
ENEMY_FRAMES = [0x0a00, 0x0a60, 0x0ac0, 0x0a00, 0x0b20, 0x0b80]    # 3 columns of 32
SKELETON = [(0x0be0, 32), (0x5da0, 24), (0x4510, 16), (0x5de8, 8)]  # (address, lines): columns of that many bytes

# nibbles that replot_tile and the level patches can put into a level, beyond the ones its map has
EXTRA_NIBBLES = {
    0: [0, 1, 2, 3], 1: [0, 1, 2, 3], 2: [0, 1, 2, 3],
    3: [0, 1, 2, 3, 4, 5, 6, 8, 0xb, 0xf], 4: [0, 1, 2, 3, 4, 5, 6, 8, 0xb, 0xf], 5: [0, 1, 2, 3, 4, 5, 6, 8, 0xb, 0xf, 7],
    6: [0, 1, 2, 3, 0xf], 7: [0, 1, 2, 3, 0xf, 0xa], 8: [0, 1, 2, 3, 0xb, 0xf],
    9: [0, 1, 2, 3, 0xe, 9], 10: [0, 1, 2, 3, 0xe], 11: [0, 1, 2, 3, 0xe],
}


def translation(mem, lv):
    """The tile translation table as the game has it in level lv: level 0 (and the completion screen) have the spaceship's
    tiles for nibbles 9, a, c and d (reset_tiles), the others what bbcmem makes of it."""
    t = bytearray(bm.translation(mem, 1 if lv == 13 else lv))
    if lv in (0, 13):
        t[0x09], t[0x0a], t[0x0c], t[0x0d] = 0x35, 0x34, 0x36, 0x37
    return t


def rd16(mem, a):
    return mem[a] | mem[a + 1] << 8


def rows_of(mem, addr, lines, bytes_per_line):
    return [[mem[addr + y * bytes_per_line + x] for x in range(bytes_per_line)] for y in range(lines)]


def cols_of(mem, addr, lines, ncols):
    return [[mem[addr + x * lines + y] for x in range(ncols)] for y in range(lines)]


def mirrored(rows):
    return [[bm.mirror_byte(b) for b in r[::-1]] for r in rows]


def swap13(b):
    out = 0
    for n in range(4):
        p = ((b >> (7 - n)) & 1) << 1 | ((b >> (3 - n)) & 1)
        p = {0: 0, 1: 3, 2: 2, 3: 1}[p]
        out |= (p >> 1) << (7 - n) | (p & 1) << (3 - n)
    return out


def sprite_blocks(rows, conv, width_cells):
    """C64 sprite blocks of an image given as lines of BBC bytes: for each run of 3 cells, the upper 21 lines then the rest"""
    blocks = []
    for c0 in range(0, width_cells, 3):
        part = [[conv[r[c]] if c < width_cells else 0 for c in range(c0, c0 + 3)] for r in rows]
        part = [[(conv[r[c]] if c < len(r) else 0) for c in range(c0, c0 + 3)] for r in rows]
        top = bytes(v for r in part[:21] for v in r) + b"\0"
        rest = part[21:]
        bot = bytes(v for r in rest for v in r)
        blocks.append((top + bytes(64))[:64])
        if rest:
            blocks.append((bot + bytes(64))[:64])
    return blocks


def db(name, data, per=16):
    out = ["%s:" % name]
    data = bytes(data)
    for i in range(0, len(data), per):
        out.append("    .byte " + ",".join("$%02x" % b for b in data[i:i + per]))
    return "\n".join(out) + "\n"


def main(outdir):
    os.makedirs(outdir, exist_ok=True)
    mem = bm.load()
    conv = make_tables.bbc_to_c64_table()
    out = ["; generated by tools/make_native_data.py\n.segment \"RODATA\"\n"]
    out.append(db("conv_table", conv))

    # --- tiles: art blocks of 128 bytes (4 columns of 32), the table tile -> (art, flags)
    arts, art_of = [], {}
    tinfo_art, tinfo_flags = [], []
    for t in range(0x39):
        lo, hi = mem[0x0f80 + 2 * t], mem[0x0f81 + 2 * t]
        base = (hi << 8) | (lo & 0xf8)
        flags = (lo & 3) | (4 if t in bm.MIRRORED_TILES else 0)
        if base not in art_of:
            art_of[base] = len(arts)
            arts.append(bytes(mem[base:base + 128]))
        tinfo_art.append(art_of[base])
        tinfo_flags.append(flags)
    out.append(db("tile_art_lo", [i * 128 & 255 for i in range(len(arts))]))
    out.append(db("tile_art_hi", [i * 128 >> 8 for i in range(len(arts))]))
    out.append(db("tile_art_index", tinfo_art))
    out.append(db("tile_flags", tinfo_flags))
    out.append(db("tile_art_data", b"".join(arts)))

    # --- levels
    tiles0, xlat, nibmask, objs, objsprites = bytearray(), bytearray(), bytearray(), bytearray(), []
    swap_levels = []
    enemy_lists = []
    enemy_offsets = []
    for lv in range(NUM_LEVELS):
        base = bm.LEVEL0_DATA - 0x100 * lv
        page = bytearray(mem[base:base + 256])
        if lv >= 1:                                       # remove_lifts_from_level_data
            for i in range(255):
                if page[i] == 0x02:
                    page[i] = page[i + 1] = 0x33
        for k in range(0, 0x54, 3):                       # initialise_levels: initial_tiles
            a, v = mem[0x40ec + k] | mem[0x40ed + k] << 8, mem[0x40ee + k]
            if (a >> 8) == 0x57 - lv:
                page[a & 255] = v
        lo_c, hi_c = bm.LEVEL_COLUMNS[lv]
        for c in range(64):
            if not lo_c <= c < hi_c:
                src = lo_c if c < lo_c else hi_c - 1
                page[c * 4:c * 4 + 4] = mem[base + src * 4:base + src * 4 + 4]
        tiles0 += page
        tr, off = translation(mem, lv), bm.level_tile_set(mem, lv)
        xlat += bytes(tr[off + n] for n in range(16))
        used = set(EXTRA_NIBBLES[lv])
        for b in page:
            used.add(b & 15)
            used.add(b >> 4)
        m = sum(1 << n for n in used)
        nibmask += bytes([m & 255, m >> 8])
        swap_levels.append(0 if mem[0x4bc0 + lv] in (0x00, 0x30) else 1)
        for i in range(4):
            flags, x, y = mem[0x03a0 + lv * 4 + i], mem[0x09a0 + lv * 4 + i], mem[0x09d0 + lv * 4 + i]
            objs += bytes([flags, x, y])
        e0, e1 = mem[0x2b6f + lv], mem[0x2b6f + lv + 1]
        enemy_offsets.append(len(enemy_lists))
        for k in range(e0, e1, 2):
            enemy_lists += [mem[0x4140 + k], mem[0x4141 + k]]
    enemy_offsets.append(len(enemy_lists))
    # level 12: the wrist terminal's, the jet pack's and the game over screens' backdrop: the 8 tile columns at &578c,
    # in tile columns 1 - 8 of a 10 column page (so it fills the 40 cells), nibbles from the quarters set (&40)
    cols = [bytes(mem[0x578c + 4 * i:0x5790 + 4 * i]) for i in range(8)]
    page = bytearray(256)
    for c in range(10):
        page[c * 4:c * 4 + 4] = cols[min(max(c - 1, 0), 7)]
    tiles0 += page
    tr, off = bm.translation(mem, 12), bm.level_tile_set(mem, 12)
    xlat += bytes(tr[off + n] if n < 8 else 0 for n in range(16))
    page12 = bytes(page)
    nm12 = sum(1 << n for n in {b & 15 for b in page} | {b >> 4 for b in page})
    used = set()
    for b in page:
        used.add(b & 15)
        used.add(b >> 4)
    m = sum(1 << n for n in used)
    nibmask += bytes([m & 255, m >> 8])
    swap_levels.append(0)
    for i in range(4):
        objs += bytes([0, 0xff, 0])
    enemy_offsets.append(len(enemy_lists))
    # level 13: the completion screen: the surface tiles with the spaceship (as level 0 has them)
    cols = [bytes(mem[0x5060 + 4 * i:0x5064 + 4 * i]) for i in range(8)]
    page = bytearray(256)
    for c in range(10):
        page[c * 4:c * 4 + 4] = cols[min(max(c - 1, 0), 7)]
    tiles0 += page
    tr, off = translation(mem, 13), bm.level_tile_set(mem, 0)
    xlat += bytes(tr[off + n] for n in range(16))
    used = {b & 15 for b in page} | {b >> 4 for b in page}
    nibmask += bytes([sum(1 << n for n in used) & 255, sum(1 << n for n in used) >> 8])
    swap_levels.append(0)
    for i in range(4):
        objs += bytes([0, 0xff, 0])
    enemy_offsets.append(len(enemy_lists))
    out.append(db("level_tiles0", tiles0, 32))
    out.append(db("level_xlat", xlat))
    out.append(db("level_nibmask", nibmask))
    out.append(db("level_objects", objs, 12))
    out.append(db("level_swap", swap_levels))
    out.append(db("level_enemies", enemy_lists))
    out.append(db("level_enemy_offsets", [o // 2 for o in enemy_offsets]))

    # --- objects: type -> sprite (column major, height bytes a column), width cells, height lines
    ot_lo, ot_hi, ot_h, ot_w, odata = [], [], [], [], bytearray()
    for t in range(16):
        a, h, w = rd16(mem, 0x934 + 4 * t), mem[0x936 + 4 * t], mem[0x937 + 4 * t]
        ot_h.append(h)
        ot_w.append(w)
        ot_lo.append(len(odata) & 255)
        ot_hi.append(len(odata) >> 8)
        odata += bytes(mem[a:a + h * w])
    out.append(db("objtype_lo", ot_lo))
    out.append(db("objtype_hi", ot_hi))
    out.append(db("objtype_h", ot_h))
    out.append(db("objtype_w", ot_w))
    out.append(db("object_data", odata))

    # --- enemy frames: BBC bytes by cell: [dir][frame 0-5 walking, 6-9 skeleton][row][col][8]; dir 0 facing right (mirrored)
    def enemy_img(rows):                     # rows: 32 lines of 3 bytes -> cells row-major
        cells = bytearray()
        for r in range(4):
            for c in range(3):
                for ln in range(8):
                    cells.append(rows[r * 8 + ln][c])
        return cells
    left, right = bytearray(), bytearray()
    imgs = [cols_of(mem, a, 32, 3) for a in ENEMY_FRAMES]
    for h_addr, h in SKELETON:
        sk = cols_of(mem, h_addr, h, 3)
        imgs.append([[0, 0, 0]] * (32 - h) + sk)
    for img in imgs:
        left += enemy_img(img)
        right += enemy_img(mirrored(img))
    out.append(db("enemy_frames_left", left, 24))

    # --- player sprites (hardware): blocks 64 bytes in the VIC bank; index table by [image][direction]
    images = []
    for a in PLAYER_STAND:
        images.append(("stand", rows_of(mem, a, 32, 3), 3))
    images.append(("kneel", rows_of(mem, PLAYER_KNEEL, 32, 3), 3))
    for a in PLAYER_CLIMB:
        images.append(("climb", rows_of(mem, a, 32, 3), 3))
    images.append(("jet", rows_of(mem, PLAYER_JET, 32, 3), 3))
    for a in PLAYER_CRAWL:
        images.append(("crawl", rows_of(mem, a, 15, 7), 7))
    images.append(("skel", cols_of(mem, 0x0be0, 32, 3), 3))
    blocks = []
    index = []
    for name, rows, w in images:
        entry = []
        for flip in (False, True):          # [0] as stored (facing left), [1] mirrored (facing right)
            r = mirrored(rows) if flip else rows
            entry.append(len(blocks))
            blocks += sprite_blocks(r, conv, w)
        index.append(entry)
    # the bullet: lines $06,$6f,$06 in the first cell
    bul = [[0x06], [0x6f], [0x06]]
    bullet_block = len(blocks)
    blocks += sprite_blocks(bul, conv, 1)
    out.append(db("sprite_index_left", [e[0] for e in index]))
    out.append(db("sprite_index_right", [e[1] for e in index]))
    out.append("SPR_BULLET = %d\nSPR_BLOCKS = %d\n" % (bullet_block, len(blocks)))
    out.append("SPR_STAND = 0\nSPR_KNEEL = 5\nSPR_CLIMB0 = 6\nSPR_CLIMB1 = 7\nSPR_JET = 8\nSPR_CRAWL0 = 9\nSPR_CRAWL1 = 10\nSPR_SKEL = 11\n")
    out.append('.segment "SPRITES"\n')
    out.append(db("sprite_blocks", b"".join(blocks), 16))
    out.append('.segment "RODATA"\n')
    # the screens' sprites (BBC bytes): column major, columns of the given height
    def blob(name, addr, n):
        out.append(db(name, bytes(mem[addr:addr + n]), 16))
    blob("spr_face", 0x4780, 4 * 32)
    blob("spr_passcard", 0x08a8, 24)
    blob("spr_cell", 0x0c40, 24)
    blob("spr_bar_left", 0x0880, 10)
    blob("spr_bar_full", 0x088a, 10)
    blob("spr_bar_empty", 0x0894, 10)
    blob("spr_bar_right", 0x089e, 10)
    blob("spr_box_top", 0x476f, 17)
    blob("spr_box_mid", 0x475e, 17)
    jet = rows_of(mem, 0x4920, 32, 3)
    out.append(db("spr_jet_u", bytes(jet[y][x] for x in range(3) for y in range(32)), 16))
    jm = mirrored(jet)
    out.append(db("spr_jet_f", bytes(jm[y][x] for x in range(3) for y in range(32)), 16))
    blob("spr_stereo", 0x0c58, 24)
    blob("spr_notes", 0x0c70, 14)
    blob("map_sprites", 0x4200, 0x39 * 8)
    blob("map_enemy", 0x0388, 8)
    # the font: glyph offsets by character - '0' (data.s font_offsets) and the glyphs, 5 bytes each
    fo = []
    text = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "bbc", "src", "data.s")).read()
    block = text[text.index("font_offsets:"):text.index("objects_x:")]
    import re
    for line in block.split("\n")[1:]:
        fo += [int(x, 16) for x in re.findall(r"\$([0-9a-f]{2})", line.split(";")[0])]
    out.append(db("font_offsets", fo[:0x2b]))
    out.append(db("font_glyphs", mem[0x5b00:0x5b00 + 0xb8], 16))
    for name, addr, n in (("text_wrist", 0x1080, 0x7e), ("text_gameover", 0x4548, 0x36), ("text_jet", 0x0300, 0x3c),
                          ("text_map", 0x442d, 0x40), ("text_na", 0x4500, 0x10), ("text_done", 0x43a0, 0x17),
                          ("text_title", 0x4700, 0x3e), ("text_jump", 0x4c80, 0x0f), ("level_names", 0x5000, 0x44),
                          ("ranking_names", 0x4ccc, 0x37), ("ranking_req", 0x4470, 8)):
        blob(name, addr, n)
    # the game over and title tunes
    out.append(db("tune_data", mem[0x0400:0x05e0], 16))
    # the SID driver's tables
    import io
    import make_sound_tables
    buf = io.StringIO()
    make_sound_tables.emit(buf)
    out.append(buf.getvalue().replace('.segment "SOUNDC"', '.segment "RODATA"'))
    # the title screen: the BBC game run to where it waits for SPACE (before its first plot of the player), its screen as characters
    from bbcsim import BBC
    b = BBC()
    assert b.run_until_pc(b.syms["title_screen_loop"], limit=400_000_000)
    ring = bytes(b.m[0x6000:0x8000])
    ss = b.screen_start()
    # shown through the wide arrangement of tools/make_title_map.py: 40 columns, 25 rows
    import make_title_map
    fw = make_title_map.forward()
    tchars, tindex, tmap = [bytes(8)], {bytes(8): 0}, []
    for cell in range(25 * 40):
        r, rc = divmod(fw[cell], make_title_map.W)
        a = ss + r * 256 + rc * 8
        if a >= 0x8000:
            a -= 0x2000
        c8 = ring[a - 0x6000:a - 0x6000 + 8]
        if c8 not in tindex:
            tindex[c8] = len(tchars)
            tchars.append(c8)
        tmap.append(tindex[c8])
    assert len(tchars) < 200, len(tchars)
    out.append("TITLE_CHARS = %d\n" % len(tchars))
    out.append(db("title_chars", b"".join(tchars), 16))
    out.append(db("title_map", bytes(tmap), 40))
    # the mine and its explosion, one cell each (BBC bytes)
    out.append(db("mine_cells", bytes(mem[0x4540:0x4548]) + bytes(mem[0x4478:0x4480]) + bytes(mem[0x4c90:0x4c98])))
    # fonts and small sprites for the screens
    out.append('.segment "CODE"\n')
    open(os.path.join(outdir, "native_data.inc"), "w").write("\n".join(out))
    print("native data: %d tile arts, %d objects bytes, %d sprite blocks, %d bytes of enemy frames"
          % (len(arts), len(odata), len(blocks), len(left) * 2))


if __name__ == "__main__":
    main(sys.argv[1])
